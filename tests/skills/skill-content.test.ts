    expect(content).toContain('at least two levels')
    expect(content).toContain('exactly one new Hypothesis')
    expect(content).toContain('terminal side branches')
    expect(content.replace(/\s+/g, ' ')).toContain('Predictions are always terminal')
    expect(content).toContain('Critique')
    expect(content).toContain('Do not promote a')
    expect(content).toContain('actual retrieval or PDF results')
    expect(content).toContain('do not produce a Draft')
    expect(content).not.toContain('Simulate & Save')
    expect(content).toContain('zero to five')
    expect(content).toContain('confidence: low')
    expect(content).toContain('incoming')
    expect(content).toContain('outgoing')
    expect(content).toContain('Focus remains unchanged')
    expect(content).toContain('explicit user request')
    expect(content).toContain('current continuation')
