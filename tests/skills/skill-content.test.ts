    const normalized = content.replace(/[`]/g, '').replace(/\s+/g, ' ')
    expect(normalized).toContain('create_question before retrieval')
    expect(normalized).toContain('create machine-reviewed Evidence before creating')
    expect(content).toContain('clear or move Focus')
    expect(content).toContain('current`, `selected`, or `focused`')
