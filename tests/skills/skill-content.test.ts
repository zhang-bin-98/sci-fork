    expect(content).toContain('create_framing_link')
    expect(content).toContain('create_evidence_assertion')
    expect(content).toContain('machine_reviewed')
    expect(content).toContain('Citation Snapshot')
    expect(content).toContain('title-only')
    expect(content).toContain('human \`reviewed\`')
    expect(content).toContain('delete_framing_link')
    expect(content).toContain('Never persist authors')
    expect(content).toContain('abstract bodies')
    expect(content).toContain('DSH Chat')
    expect(content).toContain('publicationRefs')
    expect(content).toContain('structured')
    expect(content).toContain('scientific Edge to a Question')
